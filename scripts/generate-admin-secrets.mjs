import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env");
const outPath = path.join(root, "admin-secrets.js");
const keyName = "SHOPCRAFT_SUPABASE_SERVICE_ROLE_KEY";

function parseEnvFile(fileContent) {
  const out = {};
  const lines = fileContent.split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf("=");
    if (idx === -1) continue;
    const name = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[name] = value;
  }
  return out;
}

function readServiceRoleKey() {
  if (process.env[keyName] && String(process.env[keyName]).trim()) {
    return String(process.env[keyName]).trim();
  }
  if (!fs.existsSync(envPath)) return "";
  const envVars = parseEnvFile(fs.readFileSync(envPath, "utf8"));
  return String(envVars[keyName] || "").trim();
}

const key = readServiceRoleKey();
const escaped = key.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

const output = `/**
 * Auto-generated by scripts/generate-admin-secrets.mjs.
 * Do not edit manually; set ${keyName} in .env (or environment) and rebuild.
 */
window.${keyName} = "${escaped}";
`;

fs.writeFileSync(outPath, output, "utf8");
console.log(`[generate-admin-secrets] wrote ${path.basename(outPath)} (${key ? "key set" : "empty key"})`);
